const languageSelect = document.getElementById("languageSelect");

function setLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (dict[key]) element.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    if (dict[key]) element.placeholder = dict[key];
  });

  // Update the search label for the selected language.
  const searchLabel = document.getElementById("searchInput");
  searchLabel.setAttribute("aria-label", dict.searchPlaceholder || "Search apps");
}

languageSelect.addEventListener("change", event => setLanguage(event.target.value));
setLanguage("en");

